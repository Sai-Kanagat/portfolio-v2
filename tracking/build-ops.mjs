// Packs ops/** into functions/_lib/ops-assets.js. The dashboard is served by a Function, never as static files:
// when the free daily Functions limit is reached Pages "fails open" and serves static files without any gate.
//   node tracking/build-ops.mjs          write
//   node tracking/build-ops.mjs --check  exit 1 when the packed file is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'functions/_lib/ops-assets.js');
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8' };
const assets = {};
(function walk(dir, rel) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const r = rel ? rel + '/' + e.name : e.name;
    if (e.isDirectory()) walk(path.join(dir, e.name), r);
    else if (e.isFile() && TYPES[path.extname(e.name)]) assets[r] = [TYPES[path.extname(e.name)], fs.readFileSync(path.join(dir, e.name), 'utf8')];
  }
})(path.join(ROOT, 'ops'), '');
const body = '// Generated by tracking/build-ops.mjs from ops/. Do not edit.\nexport default ' + JSON.stringify(assets, null, 0) + ';\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== body) { console.error('stale: run node tracking/build-ops.mjs'); process.exit(1); }
} else fs.writeFileSync(OUT, body);
